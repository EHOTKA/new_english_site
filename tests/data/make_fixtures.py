def content_of(spec: FixtureSpec) -> str:
    if spec.raw is not None:
        return spec.raw.replace("\n", spec.newline)
    return build_content(spec.texts, newline=spec.newline, expects_index=spec.expects_index)


def write_fixtures(directory: Path = HERE) -> List[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    written: List[Path] = []
    for spec in FIXTURES:
        path = directory / spec.name
        # utf-8-sig prepends the BOM on encode; every other codec writes plain bytes.
        path.write_bytes(content_of(spec).encode(spec.encoding))
        written.append(path)
    return written


def main(argv: Optional[List[str]] = None) -> int:
    directory = Path(argv[0]) if argv and argv[0] else HERE
    for path in write_fixtures(directory):
        print(f"wrote {path.relative_to(Path.cwd()) if path.is_relative_to(Path.cwd()) else path}"
              f" ({path.stat().st_size} bytes)")
    print(f"{len(FIXTURES)} fixtures in {directory}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
