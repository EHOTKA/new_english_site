def render_blocks(blocks: List[Tuple[int, int, str]], *, newline: str = "\n") -> str:
    """Render ``(start_ms, end_ms, text)`` triples with their own timings.

    Unlike :func:`build_content` this keeps hand-written timecodes, which is what a
    regression fixture needs: real rips do not space their cues on a metronome.
    """
    parts = [
        f"{index}{newline}{_format_timecode(start)} --> {_format_timecode(end)}{newline}{text}"
        for index, (start, end, text) in enumerate(blocks, start=1)
    ]
    return (newline + newline).join(parts) + newline


