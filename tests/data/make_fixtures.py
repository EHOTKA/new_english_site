"""
Generate the step-2 test fixtures (``.srt`` files in several encodings).

Run once before the test-suite::

    python tests/data/make_fixtures.py

The files are *generated* instead of committed because cp1252/CRLF fixtures cannot
be stored as readable text in a UTF-8 repository. Every fixture carries its
expected parse result in :data:`FIXTURES`, so the tests assert against this table
(one source of truth) rather than against duplicated literals.

Cue timings are generated by a deterministic rule (start = 1000 + 1500*i ms,
duration 2500 ms) so the time-conversion assertions are stable.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional, Tuple

HERE = Path(__file__).resolve().parent


@dataclass(frozen=True)
class FixtureSpec:
    """One .srt fixture: how to write it and what the parser must return."""

    name: str
    encoding: str
    newline: str = "\n"
    texts: List[str] = field(default_factory=list)
    raw: Optional[str] = None
    expects_index: bool = True
    #: None means "structural edge case, assert loosely".
    expect_kept: Optional[int] = None
    expect_dropped: Optional[int] = None
    expect_texts: Optional[List[str]] = None
    note: str = ""


def _format_timecode(milliseconds: int) -> str:
    hours, rest = divmod(milliseconds, 3_600_000)
    minutes, rest = divmod(rest, 60_000)
    seconds, millis = divmod(rest, 1000)
    return f"{hours:02d}:{minutes:02d}:{seconds:02d},{millis:03d}"


def build_content(texts: List[str], *, newline: str, expects_index: bool = True) -> str:
    """Render cue texts into an SRT document with generated timings.

    Cues are separated by an empty line on purpose: without it a parser reads the
    next index and timecode as part of the previous cue's text.
    """
    blocks: List[str] = []
    for index, text in enumerate(texts, start=1):
        start = 1000 + 1500 * (index - 1)
        end = start + 2500
        header = f"{index}{newline}" if expects_index else ""
        blocks.append(
            f"{header}{_format_timecode(start)} --> {_format_timecode(end)}{newline}{text}"
        )
    return (newline + newline).join(blocks) + newline


